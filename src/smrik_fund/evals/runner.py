# Directories that are regenerated by runs and must not enter the identity
# fingerprint, or every run would look like a different product state.
_GENERATED = ("data/evals", "data/", "Lunacy/runs/", ".venv", "__pycache__")


def _git(*args: str, repository_root: str | Path = ".") -> str:
	try:
		return subprocess.run(
			["git", *args],
			cwd=str(repository_root),
			capture_output=True,
			text=True,
			check=False,
			timeout=60,
		).stdout.strip()
	except (OSError, subprocess.SubprocessError):
		return ""


def repository_identity(repository_root: str | Path = ".") -> dict[str, Any]:
	"""Distinguish two different dirty working states without storing the diff."""
	head = _git("rev-parse", "HEAD", repository_root=repository_root)
	diff = _git("diff", "HEAD", repository_root=repository_root)
	status = _git("status", "--porcelain", repository_root=repository_root)
	untracked = sorted(
		line[3:]
		for line in status.splitlines()
		if line.startswith("??")
		and not any(line[3:].startswith(prefix) for prefix in _GENERATED)
	)
	return {
		"head_sha": head or None,
		"dirty": bool(status.strip()),
		"tracked_diff_sha256": hashlib.sha256(diff.encode("utf-8")).hexdigest(),
		"untracked_fingerprint": hashlib.sha256(
			"\n".join(untracked).encode("utf-8")
		).hexdigest(),
		"untracked_paths": untracked,
	}


def preflight(repository_root: str | Path = ".", *, tests: str | None) -> dict[str, Any]:
	"""Run the deterministic test gate once per invocation, not per case."""
	if not tests:
		return {"status": "SKIPPED", "reason": "no preflight target configured"}
	completed = subprocess.run(
		["python", "-m", "pytest", tests, "-q", "-p", "no:cacheprovider"],
		cwd=str(repository_root),
		capture_output=True,
		text=True,
		check=False,
	)
	tail = completed.stdout.strip().splitlines()[-1:] or [""]
	return {
		"status": "PASS" if completed.returncode == 0 else "FAIL",
		"target": tests,
		"exit_code": completed.returncode,
		"summary": tail[0],
	}


def _segment_margins(inputs: case_inputs.CaseInputs) -> list[dict[str, Any]]:
	"""Surface the deterministic margins the product was given, for the judge."""
	segments = inputs.segments
	if segments is None or "operating_margin" not in segments:
		return []
	rows = segments[segments["operating_margin"].notna()]
	columns = [
		c
		for c in (
			"segment_label",
			"period",
			"operating_margin",
			"operating_margin_bps_change",
			"segment_ref",
		)
		if c in rows
	]
	return json.loads(rows[columns].to_json(orient="records"))


def _filing_workflow(
	case: dict[str, Any],
	loaded: case_inputs.CaseInputs,
	client: Any,
	case_dir: Path,
	repository_root: str | Path,
) -> dict[str, Any]:
	"""Explain one frozen movement from the filing."""
	payload, artifact_path = investigate_finding(
		case["ticker"],
		loaded.pnl,
		loaded.filing,
		loaded.finding,
		scan_metadata=loaded.scan_metadata,
		scan_context=loaded.scan_context,
		segments=loaded.segments,
		output_root=case_dir / "product",
		client=client,
		run_id=case["case_id"],
	)
	status = _classify(payload)
	if status != "COMPLETED":
		return {"status": status, "payload": payload, "checks": [], "artifact": artifact_path}

	packet = ""
	evidence_path = payload.get("evidence_path")
	if evidence_path and Path(evidence_path).is_file():
		packet = Path(evidence_path).read_text(encoding="utf-8")
	result = FinancialInvestigationResult.model_validate(
		(payload.get("investigation") or {}).get("result") or {}
	)
	checks = [
		mechanical.check("result_schema", "PASS", critical=True),
		mechanical.evidence_refs(result, packet),
		mechanical.numeric_grounding(result, loaded.pnl, loaded.segments),
		mechanical.amount_basis(result),
		mechanical.product_validator(result, packet, _allowed_periods(payload)),
		*mechanical.diagnostics(result, payload),
	]
	return {
		"status": status,
		"payload": payload,
		"checks": checks,
		"artifact": artifact_path,
		"packet": packet,
		"judge_output": (payload.get("investigation") or {}).get("result"),
	}


def _analyst_workflow(
	case: dict[str, Any],
	loaded: case_inputs.CaseInputs,
	client: Any,
	case_dir: Path,
	repository_root: str | Path,
) -> dict[str, Any]:
	"""Propose normalization candidates from a frozen evidence packet."""
	packet = case_inputs.resolve(repository_root, case["evidence_artifact"]).read_text(
		encoding="utf-8"
	)
	try:
		result, metadata = run_analyst(
			case["ticker"],
			loaded.pnl,
			packet,
			client=client,
			evidence_ref=str(case["evidence_artifact"]),
			run_id=case["case_id"],
		)
	except AdjustmentAnalysisError as exc:
		return {
			"status": "VALIDATION_REJECTED",
			"payload": {"status": "failed", "error_message": str(exc)},
			"checks": [],
			"error": str(exc),
		}
	payload = {
		"status": "completed",
		"metadata": metadata,
		"result": result.model_dump(mode="json"),
	}
	checks = mechanical.candidate_fields(
		result.candidates,
		loaded.pnl,
		packet,
		research_request=result.research_request,
		expected=case.get("expected_candidate"),
	)
	return {
		"status": "COMPLETED",
		"payload": payload,
		"checks": checks,
		"packet": packet,
		"judge_output": payload["result"],
	}


def _scan_workflow(
	case: dict[str, Any],
	loaded: case_inputs.CaseInputs,
	client: Any,
	case_dir: Path,
	repository_root: str | Path,
) -> dict[str, Any]:
	"""Decide what deserves investigation, from the deterministic analytics."""
	try:
		result, metadata = run_analytical_scan(
			case["ticker"],
			loaded.pnl,
			client=client,
			segments=loaded.segments,
			run_id=case["case_id"],
		)
	except AnalyticalScanError as exc:
		return {
			"status": "VALIDATION_REJECTED",
			"payload": {"status": "failed", "error_message": str(exc)},
			"checks": [],
			"error": str(exc),
		}
	payload = {
		"status": "completed",
		"metadata": metadata,
		"result": result.model_dump(mode="json"),
	}
	return {
		"status": "COMPLETED",
		"payload": payload,
		"checks": [mechanical.scan_findings(result.findings)],
		"packet": "",
		"judge_output": payload["result"],
	}


def _frozen_packet(
	case: dict[str, Any], repository_root: str | Path
) -> tuple[str, Path]:
	"""Load the case-pinned packet; source integrity is checked by the runner."""
	path = case_inputs.resolve(repository_root, case["evidence_artifact"])
	return path.read_text(encoding="utf-8"), path


def _frozen_investigation_workflow(
	case: dict[str, Any],
	loaded: case_inputs.CaseInputs,
	client: Any,
	case_dir: Path,
	repository_root: str | Path,
) -> dict[str, Any]:
	"""Run one unchanged investigator call against one frozen packet."""
	packet, packet_path = _frozen_packet(case, repository_root)
	result, metadata = run_financial_investigation(
		case["ticker"],
		loaded.finding,
		loaded.pnl,
		packet,
		expected_filing_accession=case["accession"],
		segments=loaded.segments,
		client=client,
		run_id=case["case_id"],
	)
	observation = build_observed_movement(
		loaded.pnl, loaded.finding, loaded.segments
	)
	quantification = extract_period_paired_disclosures(
		loaded.pnl,
		loaded.finding,
		packet,
		observed_unit=case.get("observed_unit", "dollars"),
		segments=loaded.segments,
	)
	reconciliation = reconcile_period_pair_bridge(
		loaded.pnl,
		loaded.finding,
		packet,
		observed_unit=case.get("observed_unit", "dollars"),
		segments=loaded.segments,
	)
	payload = {
		"status": "completed",
		"arm": "one_shot",
		"metadata": metadata,
		"finding": loaded.finding.model_dump(mode="json"),
		"observed_movement": observation,
		"evidence_path": str(packet_path),
		"investigation": {
			"metadata": metadata,
			"result": result.model_dump(mode="json"),
		},
		"quantified_disclosures": quantification,
		"reconciliation": reconciliation,
	}
	trace = {
		"arm": "one_shot",
		"run_id": case["case_id"],
		"observation": observation,
		"evidence_identity": {
			"path": str(packet_path),
			"sha256": case.get("evidence_sha256"),
		},
		"deterministic_quantification": quantification,
		"deterministic_reconciliation": reconciliation,
		"final_result": result.model_dump(mode="json"),
		"call_count": 1,
	}
	trace_path = case_dir / "trace.json"
	trace_path.write_text(json.dumps(trace, indent=2) + "\n", encoding="utf-8")
	return {
		"status": "COMPLETED",
		"payload": payload,
		"checks": [
			mechanical.check("result_schema", "PASS", critical=True),
			mechanical.evidence_refs(result, packet),
			mechanical.numeric_grounding(result, loaded.pnl, loaded.segments),
			mechanical.amount_basis(result),
			mechanical.product_validator(
				result, packet, _allowed_periods(payload)
			),
			*mechanical.diagnostics(result, payload),
		],
		"artifact": trace_path,
		"packet": packet,
		"judge_output": {
			"result": result.model_dump(mode="json"),
			"quantified_disclosures": quantification,
			"reconciliation": reconciliation,
		},
	}


def _procedural_workflow(
	case: dict[str, Any],
	loaded: case_inputs.CaseInputs,
	client: Any,
	case_dir: Path,
	repository_root: str | Path,
) -> dict[str, Any]:
	"""Run the bounded decomposition -> assessment -> conclusion experiment."""
	packet, packet_path = _frozen_packet(case, repository_root)
	result, metadata, trace = run_procedural_investigation(
		case["ticker"],
		loaded.finding,
		loaded.pnl,
		packet,
		expected_filing_accession=case["accession"],
		segments=loaded.segments,
		client=client,
		observed_unit=case.get("observed_unit", "dollars"),
		run_id=case["case_id"],
		trace_path=case_dir / "trace.json",
	)
	trace["evidence_identity"]["path"] = str(packet_path)
	(Path(case_dir) / "trace.json").write_text(
		json.dumps(trace, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
	)
	quantification = trace["deterministic_quantification"]
	reconciliation = trace["deterministic_reconciliation"]
	payload = {
		"status": "completed",
		"arm": "procedural",
		"metadata": metadata,
		"finding": loaded.finding.model_dump(mode="json"),
		"observed_movement": trace["observation"],
		"evidence_path": str(packet_path),
		"investigation": {
			"metadata": metadata,
			"result": result.model_dump(mode="json"),
		},
		"quantified_disclosures": quantification,
		"reconciliation": reconciliation,
	}
	return {
		"status": "COMPLETED",
		"payload": payload,
		"checks": [
			mechanical.check("result_schema", "PASS", critical=True),
			mechanical.evidence_refs(result, packet),
			mechanical.numeric_grounding(result, loaded.pnl, loaded.segments),
			mechanical.amount_basis(result),
			mechanical.product_validator(
				result, packet, _allowed_periods(payload)
			),
			*mechanical.diagnostics(result, payload),
		],
		"artifact": case_dir / "trace.json",
		"packet": packet,
		"judge_output": {
			"result": result.model_dump(mode="json"),
			"quantified_disclosures": quantification,
			"reconciliation": reconciliation,
		},
	}


# Static dispatch: a plain mapping of workflow name to function. No registry,
# no reflection, no plugin layer.
_WORKFLOWS = {
	"filing": _filing_workflow,
	"one_shot": _frozen_investigation_workflow,
	"procedural": _procedural_workflow,
	"analyst": _analyst_workflow,
	"scan": _scan_workflow,
}


def _classify(payload: dict[str, Any]) -> str:
	if str(payload.get("status", "")).casefold() == "completed":
		return "COMPLETED"
	if str(payload.get("error_stage", "")) == "investigation":
		return "VALIDATION_REJECTED"
	return "EXECUTION_ERROR"


def _blocked_record(case: dict[str, Any]) -> dict[str, Any]:
	return {
		"case_id": case["case_id"],
		"ticker": case["ticker"],
		"suites": case.get("suites", []),
		"case_status": "BLOCKED",
		"capability": "UNAVAILABLE",
		"blocked_reason": case.get("blocked_reason"),
		"missing_prerequisite": case.get("missing_prerequisite"),
		"expected_workflow": case.get("expected_workflow"),
		"product_status": "NOT_RUN",
		"product_valid": False,
		"judge_status": "NOT_RUN",
		"qualitative_verdict": None,
		"checks": [],
		"calls": {"product": 0, "judge": 0},
	}


def run_case(
	case: dict[str, Any],
	*,
	case_dir: Path,
	repository_root: str | Path,
	client_factory: Any,
	judge_client_factory: Any | None,
	max_calls: int | None,
) -> dict[str, Any]:
	"""Execute, check, and judge exactly one case."""
	case_dir.mkdir(parents=True, exist_ok=True)
	record: dict[str, Any] = {
		"case_id": case["case_id"],
		"ticker": case["ticker"],
		"suites": case.get("suites", []),
		"case_status": "READY",
		"capability": "AVAILABLE",
		"accession": case.get("accession"),
		"filing_period": case.get("filing_period"),
		"finding_rank": case.get("finding_rank"),
		"case_dir": str(case_dir),
	}

	integrity = mechanical.source_integrity(case, repository_root)
	results: list[dict[str, Any]] = [integrity]
	if integrity["status"] == "FAIL":
		record.update(
			product_status="EXECUTION_ERROR",
			product_valid=False,
			judge_status="JUDGE_SKIPPED",
			qualitative_verdict=None,
			checks=results,
			calls={"product": 0, "judge": 0},
			error="frozen source integrity failed; product was not executed",
		)
		return record

	try:
		loaded = case_inputs.load(case, repository_root)
	except Exception as exc:  # noqa: BLE001 - captured as EXECUTION_ERROR
		(case_dir / "traceback.txt").write_text(
			traceback.format_exc(), encoding="utf-8"
		)
		record.update(
			product_status="EXECUTION_ERROR",
			product_valid=False,
			judge_status="JUDGE_SKIPPED",
			qualitative_verdict=None,
			checks=results,
			calls={"product": 0, "judge": 0},
			error=f"input load failed: {exc}",
		)
		return record

	client = RecordingClient(client_factory(), max_calls=max_calls)
	workflow = _WORKFLOWS.get(case.get("workflow", "filing"))
	if workflow is None:
		raise ValueError(f"unknown workflow: {case.get('workflow')!r}")

	outcome: dict[str, Any] = {}
	product_error: str | None = None
	try:
		outcome = workflow(case, loaded, client, case_dir, repository_root)
	except Exception as exc:  # noqa: BLE001 - captured as EXECUTION_ERROR
		(case_dir / "traceback.txt").write_text(
			traceback.format_exc(), encoding="utf-8"
		)
		product_error = str(exc)

	record["calls"] = {
		"product": client.call_count,
		"judge": 0,
		"stages": client.stage_counts(),
		"model": None if not client.calls else client.calls[-1]["model"],
	}

	if product_error is not None:
		record.update(
			product_status="EXECUTION_ERROR",
			product_valid=False,
			judge_status="JUDGE_SKIPPED",
			qualitative_verdict=None,
			checks=results,
			error=product_error,
		)
		_write_rejected(case_dir, client)
		return record

	payload = outcome.get("payload") or {}
	if outcome.get("artifact"):
		record["artifact"] = str(outcome["artifact"])
	(case_dir / "payload.json").write_text(
		json.dumps(payload, indent=2, default=str), encoding="utf-8"
	)
	status = outcome["status"]
	record["product_status"] = status

	if status != "COMPLETED":
		# The model produced output that deterministic validation rejected.
		# Preserve it for diagnosis; it never becomes product state or a score.
		_write_rejected(case_dir, client)
		record.update(
			product_valid=False,
			judge_status="JUDGE_SKIPPED",
			qualitative_verdict=None,
			checks=results,
			error=outcome.get("error") or payload.get("error_message"),
			error_stage=payload.get("error_stage"),
			rejected_output="rejected_output.json",
		)
		return record

	results.extend(outcome["checks"])
	packet = outcome.get("packet", "")
	record["checks"] = results

	product_valid = not mechanical.is_critical_failure(results)
	record["product_valid"] = product_valid
	if not product_valid:
		record.update(judge_status="JUDGE_SKIPPED", qualitative_verdict=None)
		return record

	if judge_client_factory is None:
		record.update(judge_status="JUDGE_NOT_RUN", qualitative_verdict=None)
		return record

	judge_input = judging.build_input(
		case,
		system_output=outcome.get("judge_output") or {},
		evidence_packet=packet,
		observed_movement=payload.get("observed_movement"),
		segment_margins=_segment_margins(loaded),
	)
	(case_dir / "judge_input.json").write_text(
		json.dumps(judge_input, indent=2, default=str), encoding="utf-8"
	)
	try:
		verdict = judging.run(judge_input, client=judge_client_factory())
	except Exception as exc:  # noqa: BLE001 - JUDGE_ERROR stays distinct
		(case_dir / "judge_traceback.txt").write_text(
			traceback.format_exc(), encoding="utf-8"
		)
		record.update(
			judge_status="JUDGE_ERROR",
			qualitative_verdict=None,
			judge_error=str(exc),
		)
		return record

	record["calls"]["judge"] = 1
	record.update(
		judge_status="JUDGED",
		qualitative_verdict=verdict.overall,
		judge={
			"model": JUDGE_MODEL,
			"reasoning_effort": JUDGE_REASONING_EFFORT,
			**verdict.model_dump(mode="json"),
		},
	)
	(case_dir / "judge.json").write_text(
		json.dumps(verdict.model_dump(mode="json"), indent=2), encoding="utf-8"
	)
	return record


def _allowed_periods(payload: dict[str, Any]) -> set[str]:
	periods: set[str] = set()
	for row in payload.get("observed_movement") or []:
		periods.update(str(p) for p in (row.get("periods") or {}) if p)
		for bridge in row.get("year_over_year") or []:
			for key in ("period", "previous_period"):
				if bridge.get(key):
					periods.add(str(bridge[key]))
	return periods


def _write_rejected(case_dir: Path, client: RecordingClient) -> None:
	"""Persist raw model output that never became product state."""
	raw = client.raw_outputs()
	if not raw:
		return
	(case_dir / "rejected_output.json").write_text(
		json.dumps(
			{
				"trust": "UNTRUSTED",
				"disposition": "REJECTED",
				"note": (
					"Raw structured model output captured before product "
					"validation. Never scored, never product state."
				),
				"calls": raw,
			},
			indent=2,
			default=str,
		),
		encoding="utf-8",
	)


def run_iteration(
	ticker: str | None = None,
	*,
	suite: str | None = None,
	case_id: str | None = None,
	repository_root: str | Path = ".",
	output_root: str | Path = "data/evals",
	max_calls: int | None = None,
	judge_enabled: bool = True,
	preflight_target: str | None = None,
	client_factory: Any | None = None,
	judge_client_factory: Any | None = None,
) -> dict[str, Any]:
	"""Run one full evaluation iteration and persist its record."""
	selected = discover(ticker=ticker, suite=suite, case_id=case_id)
	digest, components = definition_hash(
		selected, judge_prompt=judging.JUDGE_PROMPT, judge_schema=judging.schema()
	)

	if client_factory is None:
		def client_factory() -> Any:  # noqa: E306 - local default factory
			from dotenv import load_dotenv
			from openai import OpenAI

			load_dotenv()
			return OpenAI()

	if judge_enabled and judge_client_factory is None:
		judge_client_factory = client_factory

	iteration_id = datetime.now(UTC).strftime("%Y%m%dT%H%M%S%fZ")
	run_dir = Path(output_root) / iteration_id
	run_dir.mkdir(parents=True, exist_ok=True)

	gate = preflight(repository_root, tests=preflight_target)
	(run_dir / "preflight.json").write_text(
		json.dumps(gate, indent=2), encoding="utf-8"
	)

	records: list[dict[str, Any]] = []
	for case in selected:
		if case.get("case_status") == "BLOCKED":
			records.append(_blocked_record(case))
			continue
		records.append(
			run_case(
				case,
				case_dir=run_dir / "cases" / case["case_id"],
				repository_root=repository_root,
				client_factory=client_factory,
				judge_client_factory=judge_client_factory if judge_enabled else None,
				max_calls=max_calls,
			)
		)

	iteration = {
		"iteration_id": iteration_id,
		"timestamp_utc": datetime.now(UTC).isoformat(),
		"harness_status": "HARNESS READY",
		"selection": {"ticker": ticker, "suite": suite, "case_id": case_id},
		"definition_hash": digest,
		"definition_components": components,
		"judge": {"model": JUDGE_MODEL, "reasoning_effort": JUDGE_REASONING_EFFORT},
		"preflight": gate,
		"repository": repository_identity(repository_root),
		"calls": {
			"product": sum(r.get("calls", {}).get("product", 0) for r in records),
			"judge": sum(r.get("calls", {}).get("judge", 0) for r in records),
		},
		"cases": records,
	}

	(run_dir / "iteration.json").write_text(
		json.dumps(iteration, indent=2, default=str), encoding="utf-8"
	)
	ledger = Path(output_root) / "iterations"
	ledger.mkdir(parents=True, exist_ok=True)
	(ledger / f"{iteration_id}.json").write_text(
		json.dumps(iteration, indent=2, default=str), encoding="utf-8"
	)
	for record in records:
		case_dir = Path(record.get("case_dir") or (run_dir / "cases" / record["case_id"]))
		case_dir.mkdir(parents=True, exist_ok=True)
		(case_dir / "case.json").write_text(
			json.dumps(record, indent=2, default=str), encoding="utf-8"
		)
	iteration["paths"] = {"run_dir": str(run_dir), "output_root": str(output_root)}
	return iteration
